"""Data card: per-cell statistics plus context lengths measured under each detector's tokenizer.

The token measurements decide each detector's chunk window and stride. PHANTOM's "500-token" seed
passages are measured with its authors' tokenizer, and financial text tokenizes differently under
encoder vocabularies, so this measures rather than assumes.
"""

from __future__ import annotations

import logging

import numpy as np
import pandas as pd

from src.config import MODELS

logger = logging.getLogger(__name__)

TOKENIZERS = {
    "modernbert": MODELS["modernbert_nli"],
    "deberta_v3": MODELS["deberta_nli"],
    "flan_t5 (HHEM)": {"repo_id": "google/flan-t5-base", "revision": None},
}


def cell_stats(df: pd.DataFrame) -> dict:
    """Surface statistics for one slice: sizes, context length, answer length and period rate by label."""
    out = {
        "rows": int(len(df)),
        "pairs": int(df["pair_id"].nunique()),
        "hallucinated": int(df["label"].sum()),
        "ctx_chars_mean": float(df["context"].str.len().mean()),
        "ctx_chars_p95": float(df["context"].str.len().quantile(0.95)),
    }
    for lab, name in ((0, "faithful"), (1, "halluc")):
        sub = df[df["label"] == lab]["response"]
        out[f"resp_words_{name}"] = float(sub.str.split().str.len().mean()) if len(sub) else float("nan")
        out[f"resp_period_{name}"] = float(sub.str.strip().str.endswith(".").mean()) if len(sub) else float("nan")
    return out


def token_lengths(texts: list[str], max_texts: int = 400) -> dict[str, dict[str, float]]:
    """Token-count percentiles of ``texts`` under every tokenizer in TOKENIZERS."""
    try:
        from transformers import AutoTokenizer
    except ImportError:
        logger.warning("transformers not installed; skipping tokenizer measurements")
        return {}
    rng = np.random.default_rng(0)
    if len(texts) > max_texts:
        texts = [texts[i] for i in rng.choice(len(texts), max_texts, replace=False)]
    res = {}
    for name, spec in TOKENIZERS.items():
        tok = AutoTokenizer.from_pretrained(spec["repo_id"], revision=spec["revision"])
        n = np.array([len(tok(t, add_special_tokens=False)["input_ids"]) for t in texts])
        res[name] = {"p50": float(np.percentile(n, 50)), "p95": float(np.percentile(n, 95)), "max": float(n.max())}
    return res


def render_markdown(card: dict) -> str:
    """Render the data-card dict as a markdown document."""
    lines = ["# Data card", "", f"Generated by `python -m src.cli prepare` on {card['created']}.", ""]
    lines += ["## Slices", "", "| slice | rows | pairs | halluc | ctx chars (mean) | words faithful / halluc | ends '.' faithful / halluc |", "|---|---|---|---|---|---|---|"]
    for key, s in card["slices"].items():
        lines.append(
            f"| {key} | {s['rows']} | {s['pairs']} | {s['hallucinated']} | {s['ctx_chars_mean']:.0f} | "
            f"{s['resp_words_faithful']:.1f} / {s['resp_words_halluc']:.1f} | {s['resp_period_faithful']:.2f} / {s['resp_period_halluc']:.2f} |"
        )
    tok = card.get("tokens", {})
    if tok:
        lines += ["", "## Context length in tokens, by tokenizer", "", "| slice | tokenizer | p50 | p95 | max |", "|---|---|---|---|---|"]
        for key, per_tok in tok.items():
            for name, v in per_tok.items():
                lines.append(f"| {key} | {name} | {v['p50']:.0f} | {v['p95']:.0f} | {v['max']:.0f} |")
    lines += ["", "## Split counts (pairs)", "", "```", str(card.get("split_counts", {})), "```", ""]
    return "\n".join(lines)
